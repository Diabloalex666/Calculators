def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def save_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def merge_facts() -> dict[str, dict]:
    data = load_json(FACTS)
    by_id = {i["id"]: i for i in data["items"]}
    for fact in EXTRA_FACTS:
        if fact["id"] not in by_id:
            data["items"].append(dict(fact))
            by_id[fact["id"]] = fact
    data["updated"] = TODAY
    # link used_by
    for t in TOPICS:
        if t.get("skip_gen"):
            continue
        fids = [t["fact"]] + list(t.get("extra_facts") or [])
        for fid in fids:
            item = by_id.get(fid)
            if not item:
                continue
            used = item.setdefault("used_by", [])
            if t["id"] not in used:
                used.append(t["id"])
    save_json(FACTS, data)
    return by_id


